async def reg_department(message: types.Message, state: FSMContext):
    txt = message.text.strip()

    if txt == "⬅️ Назад":
        await Registration.fio.set()
        await message.answer("Введите ФИО:")
        return

    if txt not in DEPTS:
        await message.answer("Выберите подразделение из списка.")
        return

    await state.update_data(department=txt)
    await message.answer("Выберите должность:", reply_markup=main_menu(DEPTS[txt]))
    await Registration.job.set()


async def reg_job(message: types.Message, state: FSMContext):
    data = await state.get_data()
    dept = data.get("department")

    if message.text == "⬅️ Назад":
        await Registration.department.set()
        await message.answer("Выберите подразделение:", reply_markup=main_menu())
        return

    job = message.text.strip()
    if job not in DEPTS.get(dept, []):
        await message.answer("Выберите должность из списка.")
        return

    await state.update_data(job=job)
    await state.set_state("finish_reg")
    await message.answer("Последний шаг! Нажмите любую кнопку, чтобы завершить регистрацию.")

def register_handlers(dp: Dispatcher):
    dp.register_message_handler(reg_department, state=Registration.department)
